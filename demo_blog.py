def install_posts(get_db, logger=None):
    """Publish the demo posts and unpublish everything else (demo database only)."""
    ids = [p["id"] for p in POSTS]
    try:
        with get_db() as db:
            for p in POSTS:
                db.execute(
                    """INSERT INTO blog_posts(id,title,slug,excerpt,body,category,is_published,published_at)
                       VALUES(?,?,?,?,?,?,1,?)
                       ON CONFLICT(id) DO UPDATE SET title=excluded.title, slug=excluded.slug,
                         excerpt=excluded.excerpt, body=excluded.body, category=excluded.category,
                         is_published=1, published_at=excluded.published_at""",
                    (p["id"], p["title"], p["slug"], p["excerpt"], p["body"], p["category"], p["published_at"]),
                )
            db.execute(
                "UPDATE blog_posts SET is_published=0 WHERE id NOT IN (%s)" % ",".join("?" * len(ids)), ids
            )
    except Exception:
        if logger:
            logger.exception("demo blog install failed")
